#!/usr/bin/env python3
"""Render BENCHMARK.md from standard-benchmark-results.json.

The report used to be hand-written, which meant the README, BENCHMARK.md and the raw
JSON drifted apart -- three sets of numbers for one run. Generating it means a rerun
updates every table, and the only edited prose is the commentary below.

  scripts/bench-standard-suite.py --output results/standard-benchmark-results.json
  scripts/render-benchmark-report.py            # -> BENCHMARK.md

Acceptance length is not in the JSON (the suite reads /get_server_info, which does not
expose it), so it is parsed from the SGLang log for the window after the run started.
"""
import argparse
import json
import os
import re
import statistics
from datetime import datetime, timedelta, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def accept_stats(log_path, finished_epoch, lookback_min=45):
    """Mean/min/max accepted tokens per verification pass, after started_epoch."""
    if not log_path or not os.path.exists(log_path):
        return None
    # The suite writes its JSON when it finishes, so look BACK over the whole run
    # rather than forward from the timestamp.
    start = datetime.fromtimestamp(finished_epoch, tz=timezone.utc) - timedelta(minutes=lookback_min)
    vals = []
    for line in open(log_path, errors="replace"):
        m = re.match(r"\[(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})\]", line)
        if not m or "accept len:" not in line:
            continue
        ts = datetime.strptime(m.group(1), "%Y-%m-%d %H:%M:%S").replace(tzinfo=timezone.utc)
        if ts < start:
            continue
        v = re.search(r"accept len: ([0-9.]+)", line)
        if v:
            vals.append(float(v.group(1)))
    if not vals:
        return None
    return {
        "n": len(vals), "mean": statistics.mean(vals),
        "min": min(vals), "max": max(vals), "median": statistics.median(vals),
    }


def table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join([":---"] + [":---:"] * (len(header) - 1)) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.path.join(ROOT, "results/standard-benchmark-results.json"))
    ap.add_argument("--sglang-log", default=os.path.expanduser("~/llm/miaai/.sglang.log"))
    ap.add_argument("--out", default=os.path.join(ROOT, "BENCHMARK.md"))
    ap.add_argument("--lookback-min", type=int, default=45,
                    help="minutes of log before the run timestamp to scan for acceptance")
    a = ap.parse_args()

    d = json.load(open(a.data))
    when = datetime.fromtimestamp(d["timestamp"]).strftime("%Y-%m-%d %H:%M")
    acc = accept_stats(a.sglang_log, d["timestamp"], a.lookback_min)

    wl = d["workload_diversity"]
    cc = d["concurrency_scaling"]
    ctx = d["prompt_context_scaling"]
    pc = d["prefix_caching"]
    gl = d["generation_length_scaling"]
    th = d["thinking_comparison"]

    slow, fast = min(wl, key=lambda r: r["decode_tok_s"]), max(wl, key=lambda r: r["decode_tok_s"])
    # Do not call 16 streams the peak: it edges out 8 on aggregate while average TTFT is
    # ~20x worse. Report the best level that still answers promptly.
    usable = [r for r in cc if r["avg_ttft_ms"] < 1000] or cc
    peak = max(usable, key=lambda r: r["aggregate_tok_s"])
    hottest = max(cc, key=lambda r: r["aggregate_tok_s"])

    L = []
    W = L.append
    W(f"# Qwen3.8-27B NVFP4 + DFlash2 — benchmark report\n")
    W(f"Generated by `scripts/render-benchmark-report.py` from "
      f"[`results/standard-benchmark-results.json`](results/standard-benchmark-results.json). "
      f"Do not hand-edit the tables; rerun the suite and re-render.\n")
    W(f"- **Model / endpoint:** `{d['model']}` at `{d['endpoint']}`")
    W(f"- **Run:** {when}, single DGX Spark (GB10, 121.7 GiB unified), 262,144-token KV pool, "
      f"8 concurrent slots, thinking off unless stated\n")

    W("## Headline\n")
    W(f"- **Single-stream spread: {slow['decode_tok_s']:.1f} → {fast['decode_tok_s']:.1f} tok/s** "
      f"({fast['decode_tok_s']/slow['decode_tok_s']:.2f}×), {slow['workload'].lower()} to "
      f"{fast['workload'].lower()} — this spread *is* the speculative-decoding story.")
    W(f"- **Usable peak: {peak['aggregate_tok_s']:.1f} tok/s** at {peak['concurrency']} concurrent "
      f"streams ({peak['avg_ttft_ms']:.0f} ms TTFT). "
      + (f"{hottest['concurrency']} streams nudges aggregate to {hottest['aggregate_tok_s']:.1f} but "
         f"TTFT to {hottest['avg_ttft_ms']:.0f} ms, so it is not a win."
         if hottest['concurrency'] != peak['concurrency'] else ""))
    W(f"- **Radix cache: {pc['speedup_factor']:.2f}× faster TTFT** on a shared prefix "
      f"({pc['cold_ttft_ms']:.0f} ms cold → {pc['warm_ttft_ms']:.0f} ms warm).")
    W(f"- **Thinking costs almost nothing:** {th['thinking_off']['decode_tok_s']:.2f} tok/s off vs "
      f"{th['thinking_on']['decode_tok_s']:.2f} on.")
    if acc:
        W(f"- **Acceptance: {acc['mean']:.2f} tokens per verification pass** "
          f"(range {acc['min']:.2f}–{acc['max']:.2f} over {acc['n']} decode batches, ceiling 8).")
    W("")

    W("## 1. Workload diversity (batch 1)\n")
    W("*400 completion tokens, median of 3 runs.*\n")
    W(table(["Workload", "Decode tok/s", "TTFT (ms)", "Inter-token (ms)"],
            [[r["workload"], f"**{r['decode_tok_s']:.2f}**", f"{r['ttft_ms']:.1f}", f"{r['itl_ms']:.2f}"]
             for r in wl]))
    W(f"\nDecode rate tracks how *predictable* the output is, not how hard the task is. "
      f"Structured and mathematical output lets the block drafter land; free-form prose "
      f"does not, and you pay for the discarded draft anyway.\n")

    W("## 2. Concurrency scaling\n")
    W("*300 tokens per stream.*\n")
    W(table(["Streams", "Aggregate tok/s", "Per-stream", "Avg TTFT (ms)", "Wall (s)"],
            [[str(r["concurrency"]), f"**{r['aggregate_tok_s']:.2f}**", f"{r['per_stream_tok_s']:.2f}",
              f"{r['avg_ttft_ms']:.1f}", f"{r['wall_s']:.2f}"] for r in cc]))
    c8 = next((r for r in cc if r["concurrency"] == 8), None)
    c16 = next((r for r in cc if r["concurrency"] == 16), None)
    if c8 and c16:
        W(f"\n**Throughput plateaus at 8.** Going to 16 moves aggregate "
          f"{c8['aggregate_tok_s']:.1f} → {c16['aggregate_tok_s']:.1f} tok/s — flat — while average "
          f"TTFT degrades {c16['avg_ttft_ms']/c8['avg_ttft_ms']:.0f}× "
          f"({c8['avg_ttft_ms']:.0f} → {c16['avg_ttft_ms']:.0f} ms), because "
          f"`--max-running-requests 8` admits eight and the rest queue. Past eight you must raise "
          f"*both* that and the GDN pool (`concurrency × 5` slots); raising one alone clamps back.\n")

    W("## 3. Context scaling (prefill)\n")
    W("*Note the requested vs actual columns: the generator emits fewer tokens than asked, so read "
      "the actual figure.*\n")
    W(table(["Requested", "Actual prompt tok", "TTFT (s)", "Prefill tok/s", "Decode tok/s"],
            [[f"{r['target_prompt_tokens']:,}", f"{r['actual_prompt_tokens']:,}", f"{r['ttft_s']:.3f}",
              f"**{r['prefill_tok_s']:.1f}**", f"{r['decode_tok_s']:.1f}"] for r in ctx]))
    W(f"\nPrefill holds ~2,100–3,500 tok/s across three orders of magnitude of prompt length. The "
      f"decode column is flat and low (~{statistics.median([r['decode_tok_s'] for r in ctx]):.0f} tok/s) "
      f"because this probe asks for a *summary* — prose-shaped output, so low acceptance. It is not "
      f"comparable to table 1.\n")

    W("## 4. Radix prefix cache\n")
    W(table(["Condition", "Shared prefix tok", "TTFT"],
            [["Cold (0% hit)", f"{pc['context_tokens']:,}", f"{pc['cold_ttft_ms']:.1f} ms"],
             ["Warm (100% hit)", f"{pc['context_tokens']:,}", f"**{pc['warm_ttft_ms']:.1f} ms**"]]))
    W(f"\n**{pc['speedup_factor']:.2f}× on TTFT.** This is why concurrent subagents sharing a system prompt "
      f"cost far less than N× a single agent: the shared prefix is stored and prefilled once.\n")

    W("## 5. Decode horizon\n")
    W(table(["Requested tokens", "Actual", "Decode tok/s", "Inter-token (ms)", "Total (s)"],
            [[f"{r['target_tokens']:,}", f"{r['actual_tokens']:,}", f"**{r['decode_tok_s']:.2f}**",
              f"{r['itl_ms']:.2f}", f"{r['total_s']:.2f}"] for r in gl]))
    lo = min(r["decode_tok_s"] for r in gl); hi = max(r["decode_tok_s"] for r in gl)
    W(f"\n**No degradation to 1k tokens** — {lo:.1f}–{hi:.1f} tok/s, and non-monotonic, so the spread "
      f"is run-to-run noise rather than a trend. Neither the growing KV lookup nor the Mamba "
      f"recurrent state costs measurable speed over an agent-length reply.\n")

    W("## 6. Thinking on vs off\n")
    W(table(["Mode", "Completion tok", "Reasoning tok", "TTFT (ms)", "Decode tok/s"],
            [["Thinking off", f"{th['thinking_off']['completion_tokens']:,}", "0",
              f"{th['thinking_off']['ttft_s']*1000:.1f}", f"**{th['thinking_off']['decode_tok_s']:.2f}**"],
             ["Thinking on", f"{th['thinking_on']['completion_tokens']:,}",
              f"{th['thinking_on'].get('reasoning_tokens', 0):,}",
              f"{th['thinking_on']['ttft_s']*1000:.1f}", f"**{th['thinking_on']['decode_tok_s']:.2f}**"]]))
    W(f"\nSpeculative decoding is as effective on chain-of-thought tokens as on the answer. Thinking "
      f"costs *tokens*, not throughput — and the checkpoint defaults to `xhigh`, so disable it "
      f"explicitly with `chat_template_kwargs: {{\"enable_thinking\": false}}` unless you want it.\n")

    if acc:
        W("## 7. Speculative acceptance\n")
        W(f"Parsed from SGLang telemetry over the run window: **mean "
          f"{acc['mean']:.2f}**, median {acc['median']:.2f}, range {acc['min']:.2f}–{acc['max']:.2f} "
          f"across {acc['n']} decode batches. Block size is 8, so 8.00 is the ceiling.\n")
        W(f"That single number explains every table above: at {acc['max']:.1f} accepted tokens per "
          f"pass the model emits {acc['max']/acc['min']:.1f}× more per weight-streaming pass than at "
          f"{acc['min']:.1f}. Decode here is memory-bandwidth-bound, so accepted-tokens-per-pass is "
          f"almost the whole story.\n")

    W("## Reproducing\n")
    W("```bash\nscripts/bench-standard-suite.py \\\n"
      "    --url http://127.0.0.1:8888/v1/chat/completions \\\n"
      "    --model qwen3.8-27b-sglang \\\n"
      "    --output results/standard-benchmark-results.json\nscripts/render-benchmark-report.py\n```\n")
    W("Run on an otherwise idle machine — a co-tenant GPU job depresses the concurrency numbers "
      "badly, and an earlier round of measurements had to be discarded for exactly that reason.")

    open(a.out, "w").write("\n".join(L) + "\n")
    print(f"wrote {a.out} ({len(L)} blocks)"
          + (f", acceptance from {acc['n']} batches" if acc else ", no acceptance data"))


if __name__ == "__main__":
    main()
